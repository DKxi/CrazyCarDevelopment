def apply_progress(highest, completed):
    """Clamp browser events; progress never goes backwards."""
    if type(completed) is not int or not 1 <= completed <= len(LEVELS):
        return highest
    if completed > highest:
        return highest
    return max(highest, min(len(LEVELS), completed + 1))
